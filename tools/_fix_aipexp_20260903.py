def load(path):
    raw = open(path, "r", encoding="utf-8", newline="").read()
    return json.loads(raw), raw


def save(path, data, raw):
    out = json.dumps(data, ensure_ascii=False, indent=2).replace("\n", "\r\n")
    if raw.endswith("\r\n"):
        out += "\r\n"
    with open(path, "w", encoding="utf-8", newline="") as fh:
        fh.write(out)


def main():
    files = {}
    for fname, qid, letter, old, new in PATCHES:
        if fname not in files:
            files[fname] = load(BASE / fname)

    applied = []
    for fname, qid, letter, old, new in PATCHES:
        data, _raw = files[fname]
        qs = data["questions"] if isinstance(data, dict) else data
        q = next((x for x in qs if x["id"] == qid), None)
        if q is None:
            sys.exit(f"NG: {fname} に {qid} がない")
        if letter is None:
            target, field = q, "question"
        else:
            o = next((x for x in q["options"] if x.get("letter") == letter), None)
            if o is None:
                sys.exit(f"NG: {qid} に選択肢 {letter} がない")
            target, field = o, "explanation"
        cur = target[field]
        if cur.count(old) != 1:
            sys.exit(f"NG: {qid} {letter or 'question'} 置換前文字列が {cur.count(old)} 回一致")
        target[field] = cur.replace(old, new)
        applied.append((qid, letter or "question"))

    for fname, (data, raw) in files.items():
        save(BASE / fname, data, raw)

    print(f"適用: {len(applied)}件")
    for qid, letter in applied:
        print(f"  {qid} {letter}")


if __name__ == "__main__":
    main()
